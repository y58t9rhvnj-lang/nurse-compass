function definePattern(key: Form3PatternKey): Form3PatternDefinition {
  const guide = GUIDE[key];
  return {
    key,
    labelJa: LABEL_JA[key],
    definition: guide.definition,
    assessmentPerspectives: [...guide.assessmentPerspectives],
    informationChecklist: [...guide.informationChecklist],
  };
}

/** 表示順どおりの定義配列（UI 一覧用） */
export const FORM3_PATTERN_DEFINITIONS: readonly Form3PatternDefinition[] =
  FORM3_PATTERN_ORDER.map(definePattern);

const BY_KEY: Record<Form3PatternKey, Form3PatternDefinition> =
  FORM3_PATTERN_DEFINITIONS.reduce(
    (acc, def) => {
      acc[def.key] = def;
      return acc;
    },
    {} as Record<Form3PatternKey, Form3PatternDefinition>,
  );

export function getForm3PatternDefinition(
  key: Form3PatternKey,
): Form3PatternDefinition {
  return BY_KEY[key];
}

/** ガイド本文が未転記かどうか（定義・視点・収集のいずれかが空） */
export function isForm3PatternGuidePending(key: Form3PatternKey): boolean {
  const def = BY_KEY[key];
  return (
    def.definition.trim() === "" ||
    def.assessmentPerspectives.length === 0 ||
    def.informationChecklist.length === 0
  );
}
